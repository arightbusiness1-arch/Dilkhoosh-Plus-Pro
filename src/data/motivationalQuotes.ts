export const getAllMotivationalQuotes = (): MotivationalQuote[] => {
  if (cachedAllQuotes) return cachedAllQuotes;

  const result: MotivationalQuote[] = [...curatedMasterQuotes];

  themeFormulas.forEach((formula, formulaIdx) => {
    const { category, categoryLabel, pillar, prefixes, middles, suffixes } = formula;

    prefixes.forEach((pre, preIdx) => {
      middles.forEach((mid, midIdx) => {
        suffixes.forEach((suf, sufIdx) => {
          const id = `gen-${formulaIdx}-${preIdx}-${midIdx}-${sufIdx}`;
          const quote = `${pre} ${mid} ${suf}`;
          result.push({
            id,
            quote,
            category,
            categoryLabel,
            pillar
          });
        });
      });
    });
  });

  cachedAllQuotes = result;
  return result;
};

// Seeded PRNG for Deterministic Daily Non-Repeating Permutation
const seededRandom = (seed: number) => {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
};

const hashDateString = (dateStr: string): number => {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    const char = dateStr.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash |= 0;
  }
  return Math.abs(hash) + 12345;
};

// Generate a full permutation array of [0, 1, ..., N-1] for the specified day
export const getDailyDeckOrder = (dateStr: string, totalCount: number): number[] => {
  const seed = hashDateString(dateStr);
  const rand = seededRandom(seed);

  const deck = Array.from({ length: totalCount }, (_, i) => i);

  // Fisher-Yates shuffle with seeded PRNG
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const temp = deck[i];
    deck[i] = deck[j];
    deck[j] = temp;
  }

  return deck;
};

// Local storage key for current day tracking
const STORAGE_PREFIX = 'dilkhoosh_motivational_quote_v2_';

interface DailyQuoteState {
  date: string;
  currentIndex: number;
  shownCount: number;
}

export const getStoredDailyQuoteState = (todayStr: string): DailyQuoteState => {
  try {
    const raw = localStorage.getItem(STORAGE_PREFIX + todayStr);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && parsed.date === todayStr && typeof parsed.currentIndex === 'number') {
        return parsed;
      }
    }
  } catch (e) {
    // Ignore localStorage read errors
  }

  return {
    date: todayStr,
    currentIndex: 0,
    shownCount: 1
  };
};

export const saveStoredDailyQuoteState = (state: DailyQuoteState): void => {
  try {
    localStorage.setItem(STORAGE_PREFIX + state.date, JSON.stringify(state));
  } catch (e) {
    // Ignore localStorage write errors
  }
};
